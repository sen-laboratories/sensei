"""Writes PLUGINS.md: an overview of the plugins, generated from their Resources.rdef (signature, features, file types, relation types).

    tools/overview.py            writes PLUGINS.md
    tools/overview.py --check    changes nothing, exit code 1 when PLUGINS.md is not up to date (for CI)
"""
import glob
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
FEATURES = ['extract', 'enrich', 'identify', 'navigate', 'search']


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def plugin(path):
    text = read(os.path.join(path, 'Resources.rdef'))
    name = os.path.basename(path)
    signature = re.search(r'resource app_signature "([^"]+)"', text).group(1)
    short = re.search(r'short_info\s*=\s*"([^"]*)"', text).group(1)
    long = re.search(r'long_info\s*=\s*"([^"]*)"', text).group(1)
    major, middle, minor = (re.search(rf'{k}\s*=\s*(\d+)', text).group(1) for k in ('major', 'middle', 'minor'))
    variety = int(re.search(r'variety\s*=\s*(\d+)', text).group(1))
    features = [f for f in FEATURES if re.search(rf'"SEN:plugin:{f}"\)\s*1\b', text)]
    types_block = re.search(r'resource file_types message \{(.*?)\};', text, re.S)
    types = re.findall(r'"types"\s*=\s*"([^"]+)"', types_block.group(1)) if types_block else []
    mapping = re.search(r'"SEN:typeMapping"\) message \{(.*?)\};', text, re.S)
    relations = re.findall(r'=\s*"(relation/[^"]+)"', mapping.group(1)) if mapping else []
    makefile = read(os.path.join(path, 'Makefile'))
    binary = re.search(r'^NAME\s*=\s*(\S+)', makefile, re.M).group(1)
    return dict(name=name, signature=signature, short=short, long=long, binary=binary, features=features, types=types,
                relations=relations, version=f'{major}.{middle}.{minor}' + ('~dev' if variety == 0 else ''),
                package='sen_plugin_' + name.replace('-', '_'))


def render(plugins):
    out = ['<!-- Generated by tools/overview.py from the Resources.rdef of the plugins: do not edit. -->', '',
           '# SENSEI plugins', '',
           'One folder per plugin in `plugins/`, named for what it does; one package each. Shared code is in `common/`.', '',
           '```', 'sensei', '├── common                      code that several plugins use', '└── plugins']
    for i, p in enumerate(plugins):
        last = i == len(plugins) - 1
        branch, pad = ('└── ', '    ') if last else ('├── ', '│   ')
        out.append(f'    {branch}{p["name"]:<22}{", ".join(p["features"]) or "-"}')
    out += ['```', '',
            '| Plugin | Package | Features | Handles | Produces | Signature |', '|---|---|---|---|---|---|']
    for p in plugins:
        out.append('| `{name}` ({short}) | `{package}` {version} | {features} | {types} | {relations} | `{signature}` |'.format(
            name=p['name'], short=p['short'], package=p['package'], version=p['version'],
            features=', '.join(p['features']) or '-',
            types=', '.join(f'`{t}`' for t in p['types']) or '-',
            relations=', '.join(f'`{r}`' for r in p['relations']) or '-',
            signature=p['signature']))
    out += ['']
    for p in plugins:
        out += [f'**{p["name"]}**: {p["long"]}', '']
    return '\n'.join(out)


def main():
    paths = sorted(p for p in glob.glob(os.path.join(ROOT, 'plugins', '*')) if os.path.isfile(os.path.join(p, 'Resources.rdef')))
    text = render([plugin(p) for p in paths])
    target = os.path.join(ROOT, 'PLUGINS.md')
    if '--check' in sys.argv:
        current = read(target) if os.path.exists(target) else ''
        sys.exit(0 if current == text else 1)
    with open(target, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {target}')


if __name__ == '__main__':
    main()
